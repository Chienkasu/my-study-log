function getDailyRecipe(): Recipe {
  const now = new Date();
  // 日本時間に合わせる (UTC+9)
  const jstOffset = 9 * 60 * 60 * 1000;
  const jst = new Date(now.getTime() + jstOffset);
  const startOfYear = new Date(jst.getUTCFullYear(), 0, 0);
  const diff = jst.getTime() - startOfYear.getTime();
  const dayOfYear = Math.floor(diff / (1000 * 60 * 60 * 24));
  return RECIPES[dayOfYear % RECIPES.length];
}

function getDifficultyStars(difficulty: Recipe["difficulty"]): string {
  switch (difficulty) {
    case "かんたん": return "★☆☆";
    case "ふつう": return "★★☆";
    case "本格派": return "★★★";
  }
}

